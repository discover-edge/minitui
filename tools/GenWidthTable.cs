// Generates src/MiniTui/Text/UnicodeWidthTable.g.cs from the Unicode Character Database.
//
// Usage (from the repository root):
//   dotnet run tools/GenWidthTable.cs
//   dotnet run tools/GenWidthTable.cs -- <EastAsianWidth.txt> <emoji-data.txt>
//
// Without arguments the data files are downloaded from unicode.org.

using System.Globalization;
using System.Text;

const string UnicodeVersion = "16.0.0";
const string EastAsianWidthUrl = $"https://www.unicode.org/Public/{UnicodeVersion}/ucd/EastAsianWidth.txt";
const string EmojiDataUrl = $"https://www.unicode.org/Public/{UnicodeVersion}/ucd/emoji/emoji-data.txt";
const string OutputPath = "src/MiniTui/Text/UnicodeWidthTable.g.cs";

var eastAsianWidth = args.Length >= 2 ? File.ReadAllText(args[0]) : await Download(EastAsianWidthUrl);
var emojiData = args.Length >= 2 ? File.ReadAllText(args[1]) : await Download(EmojiDataUrl);

var wide = Merge(Parse(eastAsianWidth, value => value is "W" or "F"));
var emojiPresentation = Merge(Parse(emojiData, value => value == "Emoji_Presentation"));

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine($"// Generated by tools/GenWidthTable.cs from Unicode {UnicodeVersion}");
sb.AppendLine("// EastAsianWidth.txt and emoji-data.txt. Do not edit by hand.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine();
sb.AppendLine("namespace MiniTui;");
sb.AppendLine();
sb.AppendLine("internal static class UnicodeWidthTable");
sb.AppendLine("{");
sb.AppendLine($"    internal const string UnicodeVersion = \"{UnicodeVersion}\";");
sb.AppendLine();
WriteTable(sb, "EastAsianWide", "East_Asian_Width W or F, as inclusive [start, end] pairs.", wide);
sb.AppendLine();
WriteTable(sb, "EmojiPresentation", "Emoji_Presentation=Yes, as inclusive [start, end] pairs.", emojiPresentation);
sb.AppendLine("}");

File.WriteAllText(OutputPath, sb.ToString().ReplaceLineEndings("\n"));
Console.WriteLine($"Wrote {OutputPath}: {wide.Count} wide ranges, {emojiPresentation.Count} emoji presentation ranges.");

static async Task<string> Download(string url)
{
    using var http = new HttpClient();
    return await http.GetStringAsync(url);
}

// Parses "XXXX..YYYY ; Value # comment" lines, including "# @missing:" defaults.
static List<(int Start, int End)> Parse(string data, Func<string, bool> include)
{
    var ranges = new List<(int, int)>();
    foreach (var rawLine in data.Split('\n'))
    {
        var line = rawLine.Trim();
        if (line.StartsWith("# @missing:", StringComparison.Ordinal))
            line = line["# @missing:".Length..].Trim();
        else if (line.StartsWith('#'))
            continue;

        var hash = line.IndexOf('#');
        if (hash >= 0) line = line[..hash];
        var parts = line.Split(';', StringSplitOptions.TrimEntries);
        if (parts.Length < 2 || !include(parts[1])) continue;

        var bounds = parts[0].Split("..");
        var start = int.Parse(bounds[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
        var end = bounds.Length > 1 ? int.Parse(bounds[1], NumberStyles.HexNumber, CultureInfo.InvariantCulture) : start;
        ranges.Add((start, end));
    }
    return ranges;
}

static List<(int Start, int End)> Merge(List<(int Start, int End)> ranges)
{
    var merged = new List<(int Start, int End)>();
    foreach (var (start, end) in ranges.OrderBy(r => r.Start))
    {
        if (merged.Count > 0 && start <= merged[^1].End + 1)
            merged[^1] = (merged[^1].Start, Math.Max(merged[^1].End, end));
        else
            merged.Add((start, end));
    }
    return merged;
}

static void WriteTable(StringBuilder sb, string name, string summary, List<(int Start, int End)> ranges)
{
    sb.AppendLine($"    /// <summary>{summary}</summary>");
    sb.AppendLine($"    internal static ReadOnlySpan<uint> {name} =>");
    sb.AppendLine("    [");
    foreach (var (start, end) in ranges)
        sb.AppendLine($"        0x{start:X5}, 0x{end:X5},");
    sb.AppendLine("    ];");
}
